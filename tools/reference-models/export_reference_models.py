"""Export the img2threejs specs in reference-models/<slug>/ to src/data/referenceModels.generated.ts.

Each spec's componentTree is already in millimetres (transform.scale = size, children positioned
relative to the root). The export flattens it to world millimetres, recentres it on its bounding
box and keeps only what the build scene renders: boxes, flattened-ellipsoid discs and the
material colour/roughness/metalness/transmission. Run from the repository root:

    python tools/reference-models/export_reference_models.py
    npx prettier --write src/data/referenceModels.generated.ts
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODELS = [
    # (slug, catalog part id, frame)
    ("o11dew", "showcase-case-lianli-o11dew", "case"),
    ("msi-g507t", "showcase-gpu-msi-g507t-16gtcw", "gpu"),
]
OUT = ROOT / "src" / "data" / "referenceModels.generated.ts"


def r(value):
    return round(float(value), 2)


def export(slug, part_id, frame):
    spec = json.loads((ROOT / "reference-models" / slug / "object-sculpt-spec.json").read_text(encoding="utf-8"))
    tree = spec["componentTree"]
    by_id = {c["id"]: c for c in tree}
    parts = []
    for c in tree:
        pos = list(c["transform"]["position"])
        parent = by_id.get(c.get("parent") or "")
        while parent:
            pos = [a + b for a, b in zip(pos, parent["transform"]["position"])]
            parent = by_id.get(parent.get("parent") or "")
        shape = {"box": "box", "ellipsoid": "disc", "sphere": "disc"}[c["primitive"]]
        parts.append({"id": c["id"], "shape": shape, "sizeMm": [r(v) for v in c["transform"]["scale"]],
                      "positionMm": [r(v) for v in pos], "material": c["material"]})
    lo = [min(p["positionMm"][i] - p["sizeMm"][i] / 2 for p in parts) for i in range(3)]
    hi = [max(p["positionMm"][i] + p["sizeMm"][i] / 2 for p in parts) for i in range(3)]
    centre = [(a + b) / 2 for a, b in zip(lo, hi)]
    for p in parts:
        p["positionMm"] = [r(v - c) for v, c in zip(p["positionMm"], centre)]
    materials = {}
    for m in spec["materials"]:
        entry = {"color": m["baseColor"], "roughness": r(m["roughness"]["base"]), "metalness": r(m["metalness"]["base"])}
        transmission = m.get("transmission")
        if isinstance(transmission, dict) and transmission.get("base"):
            entry["transmission"] = r(transmission["base"])
        materials[m["id"]] = entry
    reviews = spec.get("reviewHistory", [])
    return {
        "partId": part_id,
        "slug": slug,
        "frame": frame,
        "geometryAccuracy": "reference_reconstructed",
        "source": "img2threejs",
        "envelopeMm": [r(b - a) for a, b in zip(lo, hi)],
        "passes": len({review.get("passId") for review in reviews}),
        "finalVisionScore": reviews[-1].get("aiVisionScore") if reviews else None,
        "parts": parts,
        "materials": materials,
    }


models = [export(*entry) for entry in MODELS]
body = json.dumps(models, indent=2)
OUT.write_text(
    "// Generated by tools/reference-models/export_reference_models.py from reference-models/*/object-sculpt-spec.json.\n"
    "// Do not edit by hand; rerun the script after changing a spec.\n"
    'import type { ReferenceModel } from "@/lib/v3/reference-models";\n\n'
    f"export const generatedReferenceModels: ReferenceModel[] = {body};\n",
    encoding="utf-8",
)
for m in models:
    print(m["slug"], "parts", len(m["parts"]), "envelope", m["envelopeMm"], "passes", m["passes"])
